// 台灣國定假日（內建離線表，#13）。
// 固定日期假日以「月-日」比對，適用所有年份；農曆與清明等浮動假日逐年列出。
// 目前完整涵蓋 2025–2026（今年前後），其餘年份仍會標出固定日期假日。

const FIXED: Record<string, string> = {
  '01-01': '中華民國開國紀念日（元旦）',
  '02-28': '和平紀念日',
  '04-04': '兒童節',
  '05-01': '勞動節',
  '10-10': '國慶日',
  '10-25': '臺灣光復節',
  '12-25': '行憲紀念日',
}

// 浮動假日（農曆春節/端午/中秋、清明等），以完整日期比對
const SPECIFIC: Record<string, string> = {
  // 2025
  '2025-01-28': '除夕',
  '2025-01-29': '春節（初一）',
  '2025-01-30': '春節（初二）',
  '2025-01-31': '春節（初三）',
  '2025-04-03': '清明節',
  '2025-05-31': '端午節',
  '2025-10-06': '中秋節',
  // 2026
  '2026-02-16': '除夕',
  '2026-02-17': '春節（初一）',
  '2026-02-18': '春節（初二）',
  '2026-02-19': '春節（初三）',
  '2026-04-05': '清明節',
  '2026-06-19': '端午節',
  '2026-09-25': '中秋節',
}

/** 回傳該日的國定假日名稱，非假日回傳 null。date 格式 YYYY-MM-DD。 */
export function taiwanHoliday(date: string): string | null {
  if (SPECIFIC[date]) return SPECIFIC[date]
  return FIXED[date.slice(5)] ?? null
}
